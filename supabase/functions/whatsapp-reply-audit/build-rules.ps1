# Builds rules.ts (the auditor's digest of docs/agent-rules.md, one line per R rule) from the R table.
# Run after any change to docs/agent-rules.md, then redeploy whatsapp-reply-audit:
#   powershell -File supabase/functions/whatsapp-reply-audit/build-rules.ps1
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$src = Join-Path $here '..\..\..\docs\agent-rules.md'
$lines = [System.IO.File]::ReadAllLines($src, [System.Text.Encoding]::UTF8)
$out = New-Object System.Collections.Generic.List[string]
$out.Add('// generated by build-rules.ps1 from docs/agent-rules.md - do not edit by hand')
$out.Add('export const RULES_DIGEST: string[] = [')
$dots = [string][char]0x2026
$stop = $lines.Count
for ($i = 0; $i -lt $lines.Count; $i++) { if ($lines[$i] -match '^### ') { $stop = $i; break } }  # «قواعد انلغت» and after: not current
for ($i = 0; $i -lt $stop; $i++) {
  $l = $lines[$i]
  if ($l -match '^\| R\d+ \|') {
    $cols = $l.Split('|')
    $t = $cols[1].Trim() + ': ' + ($cols[2] -replace '[*`]', '').Trim()
  } elseif ($l -match '^(- )?\*\*R\d+') {
    # rules written as paragraphs (R54, R60-R73 ...) and the fixes listed under them
    $t = ($l -replace '^- ', '' -replace '[*`]', '').Trim()
  } else { continue }
  if ($t.Length -gt 300) { $t = $t.Substring(0, 300) + $dots }
  $out.Add('  ' + (ConvertTo-Json $t -Compress) + ',')
}
$out.Add('];')
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllLines((Join-Path $here 'rules.ts'), $out, $utf8)
Write-Output ("rules: " + ($out.Count - 3))
